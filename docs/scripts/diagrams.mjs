// Keeps every diagrams/*.svg on the shared look in diagrams/theme.mjs.
//   --write  rewrite each SVG's <style data-ntd> block and the site's generated CSS
//   --check  fail if any is out of date, or an SVG breaks a rule below
// Rules: a file is <name>.en.svg or <name>.zh.svg and both exist; the root <svg> has a viewBox
// and role="img" with an aria-label; every id starts with "<name>-" (diagrams are inlined
// into pages, several per page, so ids must not collide).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { light, dark, classes } from '../diagrams/theme.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'diagrams')
const cssOut = join(root, '.vitepress/theme/diagrams.generated.css')
const kebab = (k) => '--ntd-' + k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())
const vars = (t) => Object.entries(t).map(([k, v]) => `${kebab(k)}:${v}`).join(';')
const compact = classes.trim().split('\n').join('')

const svgStyle =
  `<style data-ntd>svg{${vars(light)};font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",` +
  `"PingFang SC","Noto Sans CJK SC",sans-serif}@media (prefers-color-scheme:dark){svg{${vars(dark)}}}` +
  `${compact}</style>`
const siteCss =
  `/* Generated by docs/scripts/diagrams.mjs from docs/diagrams/theme.mjs — do not edit. */\n` +
  `.ntd{${vars(light)}}\n.dark .ntd{${vars(dark)}}\n` +
  classes.trim().split('\n').map((l) => '.ntd ' + l).join('\n') + '\n'

const mode = process.argv[2]
if (mode !== '--write' && mode !== '--check') {
  console.error('usage: diagrams.mjs --write | --check')
  process.exit(2)
}
const problems = []
const files = readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()
const names = new Set()
for (const f of files) {
  const m = f.match(/^([a-z0-9-]+)\.(en|zh)\.svg$/)
  if (!m) { problems.push(`${f}: name it <name>.en.svg / <name>.zh.svg`); continue }
  names.add(m[1])
  const path = join(dir, f)
  const src = readFileSync(path, 'utf8')
  const open = src.match(/<svg\b[^>]*>/)
  if (!open) { problems.push(`${f}: no <svg> element`); continue }
  if (!/viewBox=/.test(open[0])) problems.push(`${f}: root <svg> needs a viewBox`)
  if (!/role="img"/.test(open[0]) || !/aria-label="[^"]+"/.test(open[0]))
    problems.push(`${f}: root <svg> needs role="img" and an aria-label`)
  for (const [, id] of src.matchAll(/\bid="([^"]+)"/g))
    if (!id.startsWith(m[1] + '-')) problems.push(`${f}: id "${id}" must start with "${m[1]}-"`)
  const without = src.replace(/<style data-ntd>[\s\S]*?<\/style>/, '')
  const want = without.replace(/(<svg\b[^>]*>)/, `$1${svgStyle}`)
  if (want !== src) {
    if (mode === '--write') writeFileSync(path, want)
    else problems.push(`${f}: style block out of date — run npm run diagrams`)
  }
}
for (const n of names)
  for (const l of ['en', 'zh'])
    if (!files.includes(`${n}.${l}.svg`)) problems.push(`${n}.${l}.svg missing`)
let current = ''
try { current = readFileSync(cssOut, 'utf8') } catch {}
if (current !== siteCss) {
  if (mode === '--write') writeFileSync(cssOut, siteCss)
  else problems.push('diagrams.generated.css out of date — run npm run diagrams')
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1) }
console.log(`diagrams: ${files.length} files ok`)
